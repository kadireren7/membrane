static std::string	read_and_remove(const char *path)
{
	FILE		*f = fopen(path, "r");
	std::string	out;
	char		buf[4096];
	size_t		n;

	TEST_ASSERT(f != NULL, "could reopen a capture temp file");
	while ((n = fread(buf, 1, sizeof(buf), f)) > 0)
		out.append(buf, n);
	fclose(f);
	remove(path);
	return (out);
}

static std::string	run_cli(const std::vector<std::string> &args,
				bool want_json, int *out_rc, std::string *out_stderr = NULL)
{
	char	out_tmpl[] = "/tmp/membrane-runtime-ollama-out-XXXXXX";
	char	err_tmpl[] = "/tmp/membrane-runtime-ollama-err-XXXXXX";
	int		out_fd = mkstemp(out_tmpl);
	int		err_fd = mkstemp(err_tmpl);
	int		saved_out;
	int		saved_err;

	TEST_ASSERT(out_fd >= 0 && err_fd >= 0, "capture temp files created");
	fflush(stdout);
	fflush(stderr);
	saved_out = dup(STDOUT_FILENO);
	saved_err = dup(STDERR_FILENO);
	dup2(out_fd, STDOUT_FILENO);
	dup2(err_fd, STDERR_FILENO);
	close(out_fd);
	close(err_fd);
	*out_rc = membrane_runtime_cmd_dispatch(args, want_json);
	fflush(stdout);
	fflush(stderr);
	dup2(saved_out, STDOUT_FILENO);
	dup2(saved_err, STDERR_FILENO);
	close(saved_out);
	close(saved_err);

	std::string	err_text = read_and_remove(err_tmpl);

	if (out_stderr != NULL)
		*out_stderr = err_text;
	return (read_and_remove(out_tmpl));
}

static bool	contains(const std::string &hay, const std::string &needle)
{
	return (hay.find(needle) != std::string::npos);
}

