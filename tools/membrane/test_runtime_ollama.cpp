static void	test_malformed_version(void)
{
	membrane_runtime_descriptor_t	d;
	std::string						big(70 * 1024, 'x');

	use_mock_endpoint();
	for (const char *bad : {"not json", "{\"version\":5}", "[]",
			"{\"version\":\"\"}", "{\"version\":\"0.1\\n; rm\"}"})
	{
		reset_mock_replies();
		set_reply(&g_version_reply, 200, bad);
		membrane_ollama_describe(&d);
		TEST_ASSERT(d.availability == MEMBRANE_RUNTIME_AVAILABILITY_UNKNOWN,
			"malformed version -> availability unknown");
		TEST_ASSERT(d.health == MEMBRANE_RUNTIME_HEALTH_UNKNOWN,
			"malformed version -> health unknown");
		TEST_ASSERT(!d.version_known, "no version fabricated");
		TEST_ASSERT(contains(d.unavailable_reason, "malformed"),
			"reason says malformed");
	}
	set_reply(&g_version_reply, 404, "404 page not found");
	membrane_ollama_describe(&d);
	TEST_ASSERT(d.availability == MEMBRANE_RUNTIME_AVAILABILITY_UNAVAILABLE
		&& d.health == MEMBRANE_RUNTIME_HEALTH_INCOMPATIBLE,
		"non-2xx on /api/version -> reachable but incompatible");
	TEST_ASSERT(contains(d.unavailable_reason, "HTTP 404"),
		"reason names the status");
	set_reply(&g_version_reply, 200, "{\"version\":\"" + big + "\"}");
	membrane_ollama_describe(&d);
	TEST_ASSERT(d.availability == MEMBRANE_RUNTIME_AVAILABILITY_UNKNOWN
		&& contains(d.unavailable_reason, "size limit"),
		"an oversized response is bounded, not buffered");
}

static void	test_version_timeout_is_bounded(void)
{
	membrane_runtime_descriptor_t	d;
	auto							start = std::chrono::steady_clock::now();
	long							ms;

	reset_mock_replies();
	use_mock_endpoint();
	set_reply(&g_version_reply, 200, g_version_fixture, 3500);
	membrane_ollama_describe(&d);
	ms = (long)std::chrono::duration_cast<std::chrono::milliseconds>(
		std::chrono::steady_clock::now() - start).count();
	TEST_ASSERT(d.health == MEMBRANE_RUNTIME_HEALTH_UNREACHABLE,
		"a hung daemon is reported unreachable");
	TEST_ASSERT(ms < 3400, "the version probe gives up within its bound");
	/* Let the mock's sleeping handler finish so its log line cannot leak
	 * into a later test's request log. */
	std::this_thread::sleep_for(std::chrono::milliseconds(3500 - ms + 300));
	reset_mock_replies();
}

