typedef struct s_route_reply
{
	int			status;
	std::string	body;
	int			delay_ms;
}	route_reply_t;

static httplib::Server			*g_mock;
static std::thread				*g_mock_thread;
static int						g_mock_port;
static std::mutex				g_mock_mutex;
static std::vector<std::string>	g_mock_log;
static route_reply_t			g_version_reply;
static route_reply_t			g_tags_reply;
static route_reply_t			g_show_reply;
static std::string				g_last_show_body;

static void	reset_mock_replies(void)
{
	std::lock_guard<std::mutex>	lock(g_mock_mutex);

	g_version_reply = {200, g_version_fixture, 0};
	g_tags_reply = {200, g_tags_fixture, 0};
	g_show_reply = {200, g_show_fixture, 0};
	g_mock_log.clear();
	g_last_show_body.clear();
}

static void	reply(const route_reply_t &r, httplib::Response &res)
{
	if (r.delay_ms > 0)
		std::this_thread::sleep_for(std::chrono::milliseconds(r.delay_ms));
	res.status = r.status;
	res.set_content(r.body, "application/json; charset=utf-8");
}

static void	trap(const httplib::Request &, httplib::Response &res)
{
	/* Never expected to be reached -- the log assertion catches it. */
	res.status = 500;
	res.set_content("{\"error\":\"trap route hit\"}", "application/json");
}

static void	start_mock_server(void)
{
	reset_mock_replies();
	g_mock = new httplib::Server();
	g_mock->set_logger([](const httplib::Request &req,
			const httplib::Response &)
	{
		std::lock_guard<std::mutex>	lock(g_mock_mutex);

		g_mock_log.push_back(req.method + " " + req.path);
	});
	g_mock->Get("/api/version", [](const httplib::Request &,
			httplib::Response &res)
	{
		route_reply_t	r;

		{
			std::lock_guard<std::mutex>	lock(g_mock_mutex);
			r = g_version_reply;
		}
		reply(r, res);
	});
	g_mock->Get("/api/tags", [](const httplib::Request &,
			httplib::Response &res)
	{
		route_reply_t	r;

		{
			std::lock_guard<std::mutex>	lock(g_mock_mutex);
			r = g_tags_reply;
		}
		reply(r, res);
	});
	g_mock->Post("/api/show", [](const httplib::Request &req,
			httplib::Response &res)
	{
		route_reply_t	r;

		{
			std::lock_guard<std::mutex>	lock(g_mock_mutex);
			r = g_show_reply;
			g_last_show_body = req.body;
		}
		reply(r, res);
	});
	/* Every mutating / inference / cloud route Ollama v0.34.3 registers
	 * that this adapter must never reach. */
	for (const char *p : {"/api/generate", "/api/chat", "/api/embed",
			"/api/embeddings", "/api/pull", "/api/push", "/api/create",
			"/api/copy", "/api/me", "/api/signout",
			"/v1/chat/completions", "/v1/completions", "/v1/embeddings",
			"/v1/responses", "/v1/messages"})
		g_mock->Post(p, trap);
	g_mock->Delete("/api/delete", trap);
	g_mock->Get("/api/ps", trap);
	g_mock->Get("/api/status", trap);
	g_mock->Get("/v1/models", trap);
	g_mock_port = g_mock->bind_to_any_port("127.0.0.1");
	TEST_ASSERT(g_mock_port > 0, "mock server bound an ephemeral port");
	g_mock_thread = new std::thread([]() { g_mock->listen_after_bind(); });

	int	attempts = 0;

	while (!g_mock->is_running() && attempts < 100)
	{
		std::this_thread::sleep_for(std::chrono::milliseconds(20));
		attempts++;
	}
	TEST_ASSERT(g_mock->is_running(), "mock server became ready");
}

static void	stop_mock_server(void)
{
	g_mock->stop();
	g_mock_thread->join();
	delete g_mock_thread;
	delete g_mock;
	g_mock = NULL;
	g_mock_thread = NULL;
}

static std::string	mock_url(void)
{
	return ("http://127.0.0.1:" + std::to_string(g_mock_port));
}

static void	use_mock_endpoint(void)
{
	setenv(MEMBRANE_OLLAMA_ENDPOINT_ENV, mock_url().c_str(), 1);
}

static void	use_closed_endpoint(void)
{
	setenv(MEMBRANE_OLLAMA_ENDPOINT_ENV, "http://127.0.0.1:1", 1);
}

static std::vector<std::string>	mock_log(void)
{
	std::lock_guard<std::mutex>	lock(g_mock_mutex);

	return (g_mock_log);
}

static void	set_reply(route_reply_t *slot, int status, const std::string &body,
				int delay_ms = 0)
{
	std::lock_guard<std::mutex>	lock(g_mock_mutex);

	*slot = {status, body, delay_ms};
}

