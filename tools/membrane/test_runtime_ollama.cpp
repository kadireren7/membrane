static void	test_unavailable_descriptor(void)
{
	membrane_runtime_descriptor_t	d;

	use_closed_endpoint();
	membrane_ollama_describe(&d);
	TEST_ASSERT(std::string(d.id) == MEMBRANE_RUNTIME_ID_OLLAMA,
		"an unreachable ollama is still a known runtime");
	TEST_ASSERT(d.type == MEMBRANE_RUNTIME_TYPE_EXTERNAL, "type external");
	TEST_ASSERT(d.availability == MEMBRANE_RUNTIME_AVAILABILITY_UNAVAILABLE,
		"unreachable -> unavailable");
	TEST_ASSERT(d.health == MEMBRANE_RUNTIME_HEALTH_UNREACHABLE,
		"unreachable -> health unreachable");
	TEST_ASSERT(!d.version_known, "no version is fabricated");
	TEST_ASSERT(d.endpoint_known
		&& std::string(d.endpoint) == "http://127.0.0.1:1",
		"the probed endpoint is still reported");
	TEST_ASSERT(std::string(d.unavailable_reason)
		== "Ollama API is not reachable.", "a plain, human reason");
}

static void	test_unavailable_cli_has_no_socket_error(void)
{
	int			rc;
	std::string	err;
	std::string	out;

	use_closed_endpoint();
	out = run_cli({"list"}, false, &rc, &err);
	TEST_ASSERT(rc == MEMBRANE_EXIT_SUCCESS, "list exits 0 even when "
		"ollama is down");
	TEST_ASSERT(contains(out, "ollama") && contains(out, "unavailable"),
		"list shows ollama as unavailable");
	out = run_cli({"inspect", "ollama"}, false, &rc, &err);
	TEST_ASSERT(rc == MEMBRANE_EXIT_SUCCESS, "inspect of an unavailable "
		"ollama still succeeds (describes the adapter)");
	TEST_ASSERT(contains(out, "Status: unavailable")
		&& contains(out, "Endpoint: http://127.0.0.1:1")
		&& contains(out, "Reason\n  Ollama API is not reachable."),
		"inspect shows status, endpoint and a Reason block");
	TEST_ASSERT(!contains(out + err, "Connection") && !contains(out + err,
		"errno") && !contains(out + err, "refused"),
		"no low-level socket error text is printed");
	out = run_cli({"models", "ollama"}, true, &rc, &err);
	TEST_ASSERT(rc == MEMBRANE_EXIT_RUNTIME_ERROR, "models on a down "
		"ollama is a RUNTIME_ERROR");
	TEST_ASSERT(json::parse(out)["error"]["code"]
		== MEMBRANE_RUNTIME_ERR_UNAVAILABLE, "structured unavailable code");
}

