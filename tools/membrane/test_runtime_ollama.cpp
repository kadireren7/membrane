static void	test_endpoint_parsing(void)
{
	membrane_ollama_endpoint_t	e;

	e = membrane_ollama_parse_endpoint(MEMBRANE_OLLAMA_DEFAULT_ENDPOINT);
	TEST_ASSERT(e.ok && e.host == "127.0.0.1" && e.port == 11434
		&& e.loopback, "documented default is loopback 11434");
	e = membrane_ollama_parse_endpoint("http://localhost/");
	TEST_ASSERT(e.ok && e.port == 11434 && e.loopback
		&& e.url == "http://localhost:11434", "default port + normalize");
	e = membrane_ollama_parse_endpoint("http://[::1]:8080");
	TEST_ASSERT(e.ok && e.host == "::1" && e.port == 8080 && e.loopback
		&& e.url == "http://[::1]:8080", "bracketed IPv6 loopback");
	e = membrane_ollama_parse_endpoint("http://192.168.1.20:11434");
	TEST_ASSERT(e.ok && !e.loopback, "an explicit LAN host is NOT loopback");
	e = membrane_ollama_parse_endpoint("http://0.0.0.0:11434");
	TEST_ASSERT(e.ok && !e.loopback, "0.0.0.0 is not treated as loopback");
	for (const char *bad : {"https://127.0.0.1:11434", "127.0.0.1:11434",
			"ftp://x", "http://user:pw@127.0.0.1:11434",
			"http://127.0.0.1:11434/api", "http://127.0.0.1:0",
			"http://127.0.0.1:99999", "http://127.0.0.1:", "http://",
			"http://::1:11434", "http://127.0.0.1:11434?x=1"})
	{
		e = membrane_ollama_parse_endpoint(bad);
		TEST_ASSERT(!e.ok && !e.error.empty(), "invalid endpoint rejected");
	}
}

static void	test_endpoint_override(void)
{
	membrane_runtime_descriptor_t	d;
	membrane_ollama_endpoint_t		e;

	unsetenv(MEMBRANE_OLLAMA_ENDPOINT_ENV);
	e = membrane_ollama_resolve_endpoint();
	TEST_ASSERT(e.ok && !e.from_env && e.url == "http://127.0.0.1:11434",
		"unset -> documented loopback default");
	reset_mock_replies();
	use_mock_endpoint();
	e = membrane_ollama_resolve_endpoint();
	TEST_ASSERT(e.ok && e.from_env && e.port == g_mock_port,
		"MEMBRANE_OLLAMA_ENDPOINT overrides the default");
	membrane_ollama_describe(&d);
	TEST_ASSERT(d.availability == MEMBRANE_RUNTIME_AVAILABILITY_AVAILABLE,
		"custom local fixture endpoint works");
	TEST_ASSERT(mock_log() == std::vector<std::string>({"GET /api/version"}),
		"discovery is exactly one GET /api/version");
	setenv(MEMBRANE_OLLAMA_ENDPOINT_ENV, "https://ollama.com", 1);
	reset_mock_replies();
	membrane_ollama_describe(&d);
	TEST_ASSERT(d.availability == MEMBRANE_RUNTIME_AVAILABILITY_UNAVAILABLE
		&& d.health == MEMBRANE_RUNTIME_HEALTH_NOT_PROBED
		&& !d.endpoint_known
		&& contains(d.unavailable_reason, "MEMBRANE_OLLAMA_ENDPOINT is "
			"invalid"), "invalid override: explained, nothing probed");
}

