static void	test_read_only_and_no_inference(void)
{
	std::string	dir = make_temp_dir();
	std::string	cmd;
	int			rc;

	setenv("MEMBRANE_MODELS_PATH", (dir + "/models.json").c_str(), 1);
	setenv("MEMBRANE_SERVER_CONFIG_PATH", (dir + "/server.json").c_str(), 1);
	setenv("MEMBRANE_SYSTEMD_USER_DIR", dir.c_str(), 1);
	reset_mock_replies();
	use_mock_endpoint();
	run_cli({"list"}, false, &rc);
	run_cli({"list"}, true, &rc);
	run_cli({"inspect", "ollama"}, false, &rc);
	run_cli({"inspect", "ollama"}, true, &rc);
	run_cli({"models", "ollama"}, false, &rc);
	run_cli({"models", "ollama"}, true, &rc);
	run_cli({"model", "inspect", "ollama", "qwen2.5:7b"}, false, &rc);
	run_cli({"model", "inspect", "ollama", "qwen2.5:7b"}, true, &rc);
	run_cli({"model", "inspect", "ollama", "gpt-oss:20b-cloud"}, true, &rc);

	std::vector<std::string>	log = mock_log();

	TEST_ASSERT(!log.empty(), "the commands did reach the mock");
	for (const auto &line : log)
	{
		size_t		sp = line.find(' ');
		std::string	method = line.substr(0, sp);
		std::string	path = line.substr(sp + 1);

		TEST_ASSERT(membrane_ollama_request_allowed(method, path),
			"every request the daemon saw is on the read-only allowlist");
		TEST_ASSERT(path != "/api/generate" && path != "/api/chat"
			&& path.compare(0, 4, "/v1/") != 0,
			"no inference request was ever sent");
		TEST_ASSERT(path != "/api/pull" && path != "/api/delete"
			&& path != "/api/create" && path != "/api/copy"
			&& path != "/api/push", "no mutating request was ever sent");
	}
	cmd = "[ -z \"$(ls -A '" + dir + "' 2>/dev/null)\" ]";
	TEST_ASSERT(system(cmd.c_str()) == 0, "no registry/config/service file "
		"was created");
	cmd = "rm -rf '" + dir + "'";
	if (system(cmd.c_str()) != 0)
		fprintf(stderr, "warning: cleanup of %s failed\n", dir.c_str());
	unsetenv("MEMBRANE_MODELS_PATH");
	unsetenv("MEMBRANE_SERVER_CONFIG_PATH");
	unsetenv("MEMBRANE_SYSTEMD_USER_DIR");
}

static void	test_allowlist(void)
{
	TEST_ASSERT(membrane_ollama_request_allowed("GET", "/api/version")
		&& membrane_ollama_request_allowed("GET", "/api/tags")
		&& membrane_ollama_request_allowed("POST", "/api/show"),
		"the 3 read-only calls are allowed");
	for (const char *p : {"/api/generate", "/api/chat", "/api/pull",
			"/api/push", "/api/create", "/api/copy", "/api/embed",
			"/api/blobs/sha256:x", "/v1/chat/completions", "/api/me",
			"/api/show/../pull"})
		TEST_ASSERT(!membrane_ollama_request_allowed("POST", p),
			"mutating/inference/cloud POSTs are refused");
	TEST_ASSERT(!membrane_ollama_request_allowed("DELETE", "/api/delete")
		&& !membrane_ollama_request_allowed("GET", "/api/ps")
		&& !membrane_ollama_request_allowed("GET", "/api/show")
		&& !membrane_ollama_request_allowed("POST", "/api/tags"),
		"exact method+path match only");
}

